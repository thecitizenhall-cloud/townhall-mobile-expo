// CardCorrection — "something in this card is inaccurate". Port of the web
// components/CardCorrection.jsx, same table, same columns, same limits.
//
// A Concern Card is written by Townhall Café from the public record, not by a
// resident, so a misstatement in it is the platform's own. The web card page
// has had this route for outside visitors; the app had none, so a signed-in
// resident had no way to say a card was wrong.
//
// card_corrections (web migration 051) takes inserts from anon and signed-in
// sessions alike and lets only admins read rows back, so the insert must not
// chain .select() — that read would be refused and the submit reported as a
// failure. submitter_id is left out, as on web: the claim stands on its own.
import { useState } from "react";
import { View, Text, TextInput, Pressable, StyleSheet } from "react-native";
import { supabase } from "../lib/supabase";
import { T } from "../lib/theme";

const MIN = 10;
const MAX = 2000;

// The database counts characters (char_length); a JS string's length counts
// UTF-16 units, so five emoji would pass a .length check at 10 and then be
// refused. Count and cut by code point instead.
const chars = (v: string) => Array.from(v);

export default function CardCorrection({ cardId }: { cardId: string }) {
  const [open, setOpen] = useState(false);
  const [claim, setClaim] = useState("");
  const [email, setEmail] = useState("");
  const [busy, setBusy] = useState(false);
  const [done, setDone] = useState(false);
  const [err, setErr] = useState("");

  const tooShort = chars(claim.trim()).length < MIN;

  async function submit() {
    const c = claim.trim();
    if (chars(c).length < MIN) { setErr("Please describe what's inaccurate (at least 10 characters)."); return; }
    setBusy(true); setErr("");
    const { error } = await supabase.from("card_corrections").insert({
      concern_card_id: cardId,
      claim: chars(c).slice(0, MAX).join(""),
      contact_email: email.trim() ? email.trim().slice(0, 254) : null,
    });
    setBusy(false);
    // Never show the database's own message here; say what to do instead.
    if (error) { setErr("Couldn't submit — please email hello@townhallcafe.org."); return; }
    setDone(true);
  }

  if (done) {
    return (
      <Text style={s.done} accessibilityLiveRegion="polite">
        ✓ Thank you — your correction request was received. We review these and will amend or remove
        the card if the record supports it.
      </Text>
    );
  }

  if (!open) {
    return (
      <Pressable onPress={() => setOpen(true)} accessibilityRole="button" style={s.openLink}>
        <Text style={s.openLinkText}>Something inaccurate in this card? Request a correction</Text>
      </Pressable>
    );
  }

  return (
    <View style={s.box}>
      <Text style={s.head}>Request a correction</Text>
      <Text style={s.lede}>
        This summary is generated by Townhall Café from the public record. If it misstates a fact —
        especially about a named person — tell us what's wrong and we'll review it against the source.
      </Text>
      <TextInput
        style={s.input}
        value={claim}
        onChangeText={(v) => setClaim(chars(v).slice(0, MAX).join(""))}
        maxLength={MAX}
        multiline
        placeholder="What is inaccurate, and what does the record actually say?"
        placeholderTextColor={T.creamFaint}
        accessibilityLabel="What is inaccurate"
      />
      <TextInput
        style={[s.input, s.email]}
        value={email}
        onChangeText={setEmail}
        maxLength={254}
        keyboardType="email-address"
        autoCapitalize="none"
        autoCorrect={false}
        placeholder="Email (optional — so we can follow up)"
        placeholderTextColor={T.creamFaint}
        accessibilityLabel="Email, optional"
      />
      {err ? <Text style={s.error} accessibilityLiveRegion="polite">{err}</Text> : null}
      <View style={s.actions}>
        <Pressable onPress={() => { setOpen(false); setErr(""); }} style={s.cancel} accessibilityRole="button">
          <Text style={s.cancelText}>Cancel</Text>
        </Pressable>
        <Pressable
          onPress={submit}
          disabled={busy || tooShort}
          accessibilityRole="button"
          accessibilityState={{ disabled: busy || tooShort, busy }}
          style={[s.submit, (busy || tooShort) && s.submitOff]}>
          <Text style={s.submitText}>{busy ? "Submitting…" : "Submit correction"}</Text>
        </Pressable>
      </View>
    </View>
  );
}

const s = StyleSheet.create({
  openLink: { minHeight: 44, justifyContent: "center", marginTop: 6 },
  openLinkText: { color: T.creamFaint, fontSize: 13, textDecorationLine: "underline" },
  done: { fontSize: 13, lineHeight: 21, color: T.teal, marginTop: 14 },
  box: { borderWidth: 1, borderColor: T.border, borderRadius: 14, backgroundColor: T.surface, padding: 14, marginTop: 14 },
  head: { fontSize: 11, fontWeight: "600", color: T.amberHi, textTransform: "uppercase", letterSpacing: 0.8, marginBottom: 8 },
  lede: { fontSize: 13, lineHeight: 20, color: T.creamDim, marginBottom: 12 },
  input: { minHeight: 84, borderRadius: 8, borderWidth: 1, borderColor: T.borderCtl, backgroundColor: "#141310", color: T.cream, fontSize: 14, lineHeight: 21, padding: 10, textAlignVertical: "top" },
  email: { minHeight: 44, marginTop: 10, textAlignVertical: "center" },
  error: { marginTop: 10, fontSize: 12, color: T.redHi },
  actions: { flexDirection: "row", justifyContent: "flex-end", gap: 10, marginTop: 14 },
  cancel: { minHeight: 44, justifyContent: "center", paddingHorizontal: 16, borderRadius: 9, borderWidth: 1, borderColor: T.border },
  cancelText: { color: T.creamDim, fontSize: 13 },
  submit: { minHeight: 44, justifyContent: "center", paddingHorizontal: 18, borderRadius: 9, backgroundColor: T.amber },
  submitOff: { opacity: 0.6 },
  submitText: { color: T.bg, fontSize: 13, fontWeight: "600" },
});
